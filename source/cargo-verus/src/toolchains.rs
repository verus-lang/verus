#[cfg(test)]
mod tests {
    use super::*;
    use cargo_metadata::semver::Version;

    const VERUS_GIT_URL: &str = "https://github.com/verus-lang/verus.git";

    /// A commit hash, and the abbreviation a toolchain manifest would name it by.
    const FULL_REV: &str = "31579f0b8542a8a9ae4ae5604c16107ccde23ef2";
    const ABBREVIATED_REV: &str = "31579f0";

    fn known_git(rev: &'static str) -> Crate {
        Crate::GitCommit { git: VERUS_GIT_URL, rev }
    }

    fn used_git(url: &str, rev: Option<&str>) -> PackageMetadata {
        PackageMetadata {
            version: Version::parse("0.0.0-2026-07-12-0122").expect("valid version"),
            source: PackageSource::Git { url: url.to_owned(), rev: rev.map(ToOwned::to_owned) },
        }
    }

    /// The regression: a manifest abbreviates the revision, Cargo resolves the
    /// dependency to the full commit hash, and the two still have to pair up.
    #[test]
    fn abbreviated_known_rev_matches_full_used_rev() {
        assert!(is_matching_known_and_used(
            &known_git(ABBREVIATED_REV),
            &used_git(VERUS_GIT_URL, Some(FULL_REV)),
        ));
    }

    #[test]
    fn identical_revs_match() {
        assert!(is_matching_known_and_used(
            &known_git(FULL_REV),
            &used_git(VERUS_GIT_URL, Some(FULL_REV)),
        ));
    }

    #[test]
    fn revs_differing_in_the_abbreviated_part_do_not_match() {
        assert!(!is_matching_known_and_used(
            &known_git("31579f1"),
            &used_git(VERUS_GIT_URL, Some(FULL_REV)),
        ));
    }

    #[test]
    fn differing_urls_do_not_match() {
        assert!(!is_matching_known_and_used(
            &known_git(ABBREVIATED_REV),
            &used_git("https://github.com/verus-lang/fork.git", Some(FULL_REV)),
        ));
    }

    #[test]
    fn a_used_source_without_a_rev_does_not_match() {
        assert!(!is_matching_known_and_used(
            &known_git(ABBREVIATED_REV),
            &used_git(VERUS_GIT_URL, None),
        ));
    }

    #[test]
    fn rev_case_is_ignored() {
        assert!(is_matching_rev(&ABBREVIATED_REV.to_uppercase(), FULL_REV));
        assert!(is_matching_rev(ABBREVIATED_REV, &FULL_REV.to_uppercase()));
    }

    /// Guard against a prefix so short it could pair unrelated commits.
    #[test]
    fn a_rev_below_the_minimum_length_does_not_match() {
        assert!(!is_matching_rev(&FULL_REV[..MIN_ABBREVIATED_REV_LEN - 1], FULL_REV));
        assert!(is_matching_rev(&FULL_REV[..MIN_ABBREVIATED_REV_LEN], FULL_REV));
    }

    #[test]
    fn a_rev_longer_than_a_commit_hash_does_not_match() {
        assert!(!is_matching_rev(FULL_REV, &format!("{FULL_REV}0")));
    }

    /// A revision that cannot be a commit hash is only ever matched exactly.
    #[test]
    fn a_non_hex_rev_matches_only_itself() {
        assert!(is_matching_rev("release/1.0", "release/1.0"));
        assert!(!is_matching_rev("release", "release/1.0"));
    }
}
