use crate::metadata::{PackageMetadata, PackageSource};

pub type Toolchain = cargo_verus_toolchains::Toolchain<&'static str>;
pub type Crate = cargo_verus_toolchains::Crate<&'static str>;

/// The number of hexadecimal digits in a full commit hash.
const FULL_REV_LEN: usize = 40;

/// The fewest hexadecimal digits an abbreviated revision may have and still be
/// considered a match. This is Git's default abbreviation length.
const MIN_ABBREVIATED_REV_LEN: usize = 7;

pub fn is_matching_known_and_used(known: &Crate, used: &PackageMetadata) -> bool {
    match (known, &used.source) {
        (Crate::Registry(known_version), PackageSource::Registry { .. }) => {
            known_version == &used.version.to_string()
        }
        (
            Crate::GitCommit { git: known_url, rev: known_rev },
            PackageSource::Git { url: ref used_url, rev: Some(ref used_rev) },
        ) => known_url == used_url && is_matching_rev(known_rev, used_rev),
        _ => false,
    }
}

/// Compare a revision named by a toolchain manifest with one reported by Cargo.
///
/// A toolchain manifest may abbreviate a revision, and `create-manifest` writes
/// an abbreviated one, but Cargo always resolves a Git dependency to the full
/// commit hash. Comparing the two for equality would reject every Git-paired
/// toolchain, because no manifest can name a revision Cargo would echo back.
/// So follow Git's rule for abbreviated object names instead: the shorter
/// revision has to be a prefix of the longer one.
fn is_matching_rev(known: &str, used: &str) -> bool {
    if known == used {
        return true;
    }

    let (short, long) = if known.len() < used.len() { (known, used) } else { (used, known) };

    // Only a commit hash can be abbreviated. Anything else, such as a tag or a
    // branch name, has to match exactly, which the check above already covers.
    let is_hex = |rev: &str| rev.as_bytes().iter().all(u8::is_ascii_hexdigit);

    (MIN_ABBREVIATED_REV_LEN..=FULL_REV_LEN).contains(&short.len())
        && long.len() <= FULL_REV_LEN
        && is_hex(short)
        && is_hex(long)
        && long[..short.len()].eq_ignore_ascii_case(short)
}

