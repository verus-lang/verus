impl<'a, 'tcx> Visitor<'tcx> for Walker<'a, 'tcx> {
    type NestedFilter = rustc_middle::hir::nested_filter::OnlyBodies;

    fn maybe_tcx(&mut self) -> TyCtxt<'tcx> {
        self.tcx
    }

    fn visit_nested_body(&mut self, id: BodyId) {
        let owner = self.tcx.hir_body_owner_def_id(id);
        let typeck = self.tcx.typeck(owner);
        self.typeck.push(typeck);
        let body = self.tcx.hir_body(id);
        self.visit_body(body);
        self.typeck.pop();
    }

    fn visit_expr(&mut self, e: &'tcx Expr<'tcx>) {
        let saved = self.exec;
        if let Some(info) = self.exec_info {
            if let Some(x) = info.hir_exec.get(&e.hir_id) {
                self.exec = *x;
            }
            if info.erased_trees.contains(&e.hir_id) {
                self.exec = false;
            }
        }
        if let ExprKind::Loop(..) = &e.kind {
            self.loop_exec.insert(e.hir_id, self.exec);
        }
        self.record_expr(e);
        if let ExprKind::Closure(_) = &e.kind {
            let loc = self.loc(e.span);
            self.body_stack.push((loc, self.exec));
            intravisit::walk_expr(self, e);
            self.body_stack.pop();
        } else {
            intravisit::walk_expr(self, e);
        }
        self.exec = saved;
    }

    fn visit_pat(&mut self, p: &'tcx Pat<'tcx>) {
        let saved = self.exec;
        if let Some(info) = self.exec_info {
            if let Some(x) = info.pat_exec.get(&p.hir_id) {
                self.exec = *x;
            }
        }
        self.record_pat(p);
        intravisit::walk_pat(self, p);
        self.exec = saved;
    }

    fn visit_local(&mut self, l: &'tcx LetStmt<'tcx>) {
        if self.exec {
            let pat_exec = self.sub_pat_exec(l.pat, true);
            if pat_exec {
                if let Some(loc) = self.user_loc(l.span) {
                    let (s, _) = self.shape(l.pat, true);
                    let s = format!("let {s}{}", if l.els.is_some() { " else" } else { "" });
                    self.push(loc, "let-stmt", FactKind::Shape, (s.clone(), s));
                }
            }
        }
        intravisit::walk_local(self, l);
    }
}

/// Build the table for one body owner (and its closures).
fn build_body_table<'tcx>(
    tcx: TyCtxt<'tcx>,
    def_id: LocalDefId,
    exec_info: Option<&ExecInfo>,
) -> Option<BodyTable> {
    let body: &'tcx Body<'tcx> = tcx.hir_maybe_body_owned_by(def_id)?;
    let typeck = tcx.typeck(def_id);
    if typeck.tainted_by_errors.is_some() {
        return None;
    }
    let sm = tcx.sess.source_map();
    if !is_user_body(tcx, def_id, body) {
        return None;
    }
    let body_loc = loc_of(sm, body.value.span)?;
    let key = body_key(tcx, def_id, body, body_loc.clone());
    let mut w = Walker {
        tcx,
        sm,
        typeck: vec![typeck],
        typing_env: ty::TypingEnv::non_body_analysis(tcx, def_id),
        exec_info,
        exec: true,
        body_stack: vec![(Some(body_loc.clone()), true)],
        loop_exec: HashMap::new(),
        table: BodyTable {
            owner: no_paths(|| tcx.def_path_str(def_id.to_def_id())),
            body: Some(body_loc),
            key,
            nodes: BTreeMap::new(),
        },
    };
    w.visit_body(body);
    Some(w.table)
}

/// Verify run: build the table for every exec body owner whose body Verus verifies.
pub fn build_verify_table<'tcx>(
    tcx: TyCtxt<'tcx>,
    bodies: &[(LocalDefId, vir::ast::Mode, bool)],
    exec_info: &ExecInfo,
) -> Table {
    let mut table = Table::default();
    let mut seen = HashSet::new();
    for (def_id, mode, has_body) in bodies {
        if *mode != vir::ast::Mode::Exec || !*has_body || !seen.insert(*def_id) {
            continue;
        }
        if tcx.is_typeck_child(def_id.to_def_id()) {
            continue;
        }
        if let Some(t) = build_body_table(tcx, *def_id, Some(exec_info)) {
            table.bodies.push(t);
        }
    }
    table
}

/// Rule 2 for bodies: the body of a function must be a block written in the source (its text
/// starts with `{`). A proc macro that emits a function with a body spanned by some other user
/// token (for example the `struct` item `exec_spec!` translates) produces a body that is not
/// the user's; such bodies are left out of both tables.
fn is_user_body<'tcx>(tcx: TyCtxt<'tcx>, def_id: LocalDefId, body: &Body<'tcx>) -> bool {
    match tcx.def_kind(def_id) {
        DefKind::Fn | DefKind::AssocFn => {
            match tcx.sess.source_map().span_to_snippet(body.value.span) {
                Ok(s) => s.trim_start().starts_with('{'),
                Err(_) => false,
            }
        }
        _ => true,
    }
}

fn body_key<'tcx>(
    tcx: TyCtxt<'tcx>,
    def_id: LocalDefId,
    body: &Body<'tcx>,
    loc: Loc,
) -> (Loc, String) {
    if body.value.span.from_expansion() {
        // identify the owner by its parent's path and its name, with the unerased-proxy prefix
        // removed as rust_to_vir_func::fixup_unerased_proxy_path does to name the VIR function
        let parent = tcx.parent(def_id.to_def_id());
        let parent = no_paths(|| tcx.def_path_str(parent));
        let name = tcx.opt_item_name(def_id.to_def_id()).map(|n| n.to_string()).unwrap_or_default();
        let name = name.strip_prefix("VERUS_UNERASED_PROXY__").unwrap_or(&name).to_string();
        (loc, format!("{parent}::{name}"))
    } else {
        (loc, String::new())
    }
}

/// Compile run: build the tables of the body owners whose body location matches a verified body.
pub fn build_compile_table<'tcx>(tcx: TyCtxt<'tcx>, verified: &Table) -> Table {
    let sm = tcx.sess.source_map();
    let wanted: HashSet<&(Loc, String)> = verified.bodies.iter().map(|b| &b.key).collect();
    let mut table = Table::default();
    for def_id in tcx.hir_body_owners() {
        if tcx.is_typeck_child(def_id.to_def_id()) {
            continue;
        }
        let Some(body) = tcx.hir_maybe_body_owned_by(def_id) else { continue };
        let Some(loc) = loc_of(sm, body.value.span) else { continue };
        let key = body_key(tcx, def_id, body, loc);
        if !wanted.contains(&key) {
            continue;
        }
        if let Some(t) = build_body_table(tcx, def_id, None) {
            table.bodies.push(t);
        }
    }
    table
}

pub struct Difference {
    pub loc: Loc,
    pub msg: String,
}

fn group(facts: &[Fact]) -> BTreeMap<FactKind, Vec<&Fact>> {
    let mut m: BTreeMap<FactKind, Vec<&Fact>> = BTreeMap::new();
    for f in facts {
        m.entry(f.kind).or_default().push(f);
    }
    for v in m.values_mut() {
        v.sort_by(|a, b| a.cmp.cmp(&b.cmp));
        v.dedup_by(|a, b| a.cmp == b.cmp);
    }
    m
}

fn show_list(v: &[&Fact]) -> String {
    let s: Vec<&str> = v.iter().map(|f| f.show.as_str()).collect();
    s.join(", ")
}

pub fn diff_tables(verified: &Table, compiled: &Table) -> Vec<Difference> {
    let mut diffs = vec![];
    // several compiled bodies may share a location (none expected); merge them
    let mut cmap: HashMap<&(Loc, String), Vec<&BodyTable>> = HashMap::new();
    for b in &compiled.bodies {
        cmap.entry(&b.key).or_default().push(b);
    }
    let mut done: BTreeSet<&(Loc, String)> = BTreeSet::new();
    for vb in &verified.bodies {
        let bkey = &vb.key;
        let bloc = &bkey.0;
        if !done.insert(bkey) {
            continue;
        }
        let Some(cbs) = cmap.get(bkey) else {
            diffs.push(Difference {
                loc: bloc.clone(),
                msg: format!(
                    "the body of `{}` is verified as exec code but the compiled program has no function with this body",
                    vb.owner
                ),
            });
            continue;
        };
        // S1: several compiled bodies with this location (the `#[verus_spec(with)]` pair `f` /
        // `_VERUS_VERIFIED_f`): drop the ones with no source-written expression other than the
        // body block itself (Erase replaces the verified twin's body by `unimplemented!()`).
        let cbs: Vec<&BodyTable> = if cbs.len() > 1 {
            cbs.iter()
                .copied()
                .filter(|b| {
                    b.nodes.keys().any(|(l, class)| {
                        l.via.is_empty() && *class != "pat-binding" && Some(l) != b.body.as_ref()
                    })
                })
                .collect()
        } else {
            cbs.clone()
        };
        // merge verified bodies with this location too
        let vbs: Vec<&BodyTable> = verified.bodies.iter().filter(|b| &b.key == bkey).collect();
        let mut vnodes: BTreeMap<&(Loc, &'static str), Vec<Fact>> = BTreeMap::new();
        for b in vbs {
            for (k, v) in &b.nodes {
                vnodes.entry(k).or_default().extend(v.iter().cloned());
            }
        }
        let mut cnodes: BTreeMap<&(Loc, &'static str), Vec<Fact>> = BTreeMap::new();
        for b in cbs {
            for (k, v) in &b.nodes {
                cnodes.entry(k).or_default().extend(v.iter().cloned());
            }
        }
        let keys: BTreeSet<&&(Loc, &'static str)> = vnodes.keys().chain(cnodes.keys()).collect();
        let empty = vec![];
        for key in keys {
            let vf = vnodes.get(*key).unwrap_or(&empty);
            let cf = cnodes.get(*key).unwrap_or(&empty);
            let vg = group(vf);
            let cg = group(cf);
            let kinds: BTreeSet<&FactKind> = vg.keys().chain(cg.keys()).collect();
            for kind in kinds {
                let vs = vg.get(kind);
                let cs = cg.get(kind);
                match (vs, cs) {
                    (Some(vs), Some(cs)) => {
                        let va: Vec<&String> = vs.iter().map(|f| &f.cmp).collect();
                        let ca: Vec<&String> = cs.iter().map(|f| &f.cmp).collect();
                        if va == ca {
                            continue;
                        }
                        // S3: a verified `(T, Ghost<..>, ..)` (ghost outputs) matches a compiled `T`
                        let mut va3: Vec<&String> = vs
                            .iter()
                            .map(|f| match &f.alt {
                                Some(a) if ca.contains(&a) && !ca.contains(&&f.cmp) => a,
                                _ => &f.cmp,
                            })
                            .collect();
                        va3.sort();
                        va3.dedup();
                        if va3 == ca {
                            continue;
                        }
                        // S5: a block that is `!` in the verified program and `()` in the compiled
                        // program: Keep appends ghost statements after the user's diverging tail
                        // (e.g. `open_invariant_end(..)` in open_local_invariant!), Erase does not.
                        // The diverging exec statement is itself compared.
                        if key.1 == "Block"
                            && matches!(kind, FactKind::Type)
                            && va.len() == 1
                            && va[0] == "!"
                            && ca.len() == 1
                            && ca[0] == "()"
                        {
                            continue;
                        }
                        diffs.push(Difference {
                            loc: key.0.clone(),
                            msg: format!(
                                "{} {} (compiled) vs {} (verified)",
                                kind.describe(),
                                show_list(cs),
                                show_list(vs)
                            ),
                        });
                    }
                    (Some(vs), None) => {
                        let rep: Vec<&Fact> = vs.iter().copied().filter(|f| f.one_sided).collect();
                        if rep.len() > 0 {
                            diffs.push(Difference {
                                loc: key.0.clone(),
                                msg: format!(
                                    "{} {} is exec control flow in the verified program, but the compiled program has no such node",
                                    kind.describe(),
                                    show_list(&rep)
                                ),
                            });
                        }
                    }
                    (None, _) => {}
                }
            }
        }
    }
    diffs
}

/// Compile run: build the compiled table, diff it against the verified table, report errors.
/// Returns the number of differences.
pub fn check_compile_run<'tcx>(tcx: TyCtxt<'tcx>, verified: &Table) -> usize {
    let compiled = build_compile_table(tcx, verified);
    let diffs = diff_tables(verified, &compiled);
    let sm = tcx.sess.source_map();
    // VERUS_CHECK_ERASURE_DUMP=1 prints both tables (to debug a reported difference)
    if std::env::var("VERUS_CHECK_ERASURE_DUMP").is_ok() {
        dump_table(sm, "verified", verified);
        dump_table(sm, "compiled", &compiled);
    }
    for d in &diffs {
        let via = if d.loc.via.is_empty() {
            String::new()
        } else {
            format!(" [in the macro expansion {}]", d.loc.via)
        };
        let msg = format!(
            "erasure check: the compiled program differs from the verified program: {}{via}",
            d.msg
        );
        match span_of_loc(sm, &d.loc) {
            Some(span) => {
                tcx.dcx().struct_span_err(span, msg).emit();
            }
            None => {
                tcx.dcx().struct_err(format!("{msg} (at {})", loc_to_string(sm, &d.loc))).emit();
            }
        }
    }
    diffs.len()
}

fn dump_table(sm: &SourceMap, which: &str, t: &Table) {
    for b in &t.bodies {
        eprintln!("== {which} body {} {:?}", b.owner, b.key);
        for ((loc, class), facts) in &b.nodes {
            for f in facts {
                eprintln!(
                    "   {} [{}-{}] {class} {:?}: {}{}",
                    loc_to_string(sm, loc),
                    loc.lo,
                    loc.hi,
                    f.kind,
                    f.cmp,
                    if f.one_sided { " (one-sided)" } else { "" }
                );
            }
        }
    }
}
