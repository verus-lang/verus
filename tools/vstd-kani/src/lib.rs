// ===========================================================================
// RangeInclusive bounds (#2674)
// ---------------------------------------------------------------------------
// vstd (`std_specs/range.rs`) models a `RangeInclusive` by its view `{ start, end,
// exhausted }`. `RangeInclusive::new` gives `{ start, end, exhausted: false }`. A range is
// empty (`spec_range_inclusive_is_empty`) when it is exhausted or `start > end`; then
// `start_bound`/`end_bound` are unspecified and, for a totally ordered `Idx`, it contains
// nothing (`axiom_range_inclusive_empty_contains`). Otherwise the bounds are
// `Included(start)`/`Included(end)`.
//
// #2674: the spec once claimed `end_bound() == Included(end)` unconditionally. After
// iteration had exhausted the range, std 1.98 returned `Excluded(end)`. Since Rust 1.99,
// `next` steps `start` past `end` instead of setting `exhausted` (except on overflow), so
// `end_bound()` is `Included(end)` again. The current spec leaves the bounds of an empty
// range unspecified, which holds for both. The harnesses below check what the current spec
// does say, on fresh and on iterated ranges.
// ===========================================================================

fn bound_owned(b: Bound<&u8>) -> Bound<u8> {
    match b {
        Bound::Included(&x) => Bound::Included(x),
        Bound::Excluded(&x) => Bound::Excluded(x),
        Bound::Unbounded => Bound::Unbounded,
    }
}

/// The current spec's claims about a fresh range `lo..=hi`.
fn range_inclusive_fresh_spec_holds(lo: u8, hi: u8) -> bool {
    let r: RangeInclusive<u8> = lo..=hi;
    // `is_empty`: exhausted (false for a fresh range) or out of order
    if r.is_empty() != (lo > hi) {
        return false;
    }
    if !r.is_empty() {
        bound_owned(r.start_bound()) == Bound::Included(lo)
            && bound_owned(r.end_bound()) == Bound::Included(hi)
    } else {
        true
    }
}

/// The current spec's claims about `lo..=hi` after `steps` calls of `next`: the items are
/// `lo, lo + 1, ..` (as many as the range has, `remaining`); once they are used up the range
/// is empty and contains nothing.
fn range_inclusive_iterated_spec_holds(lo: u8, hi: u8, steps: u8, x: u8) -> bool {
    let mut r: RangeInclusive<u8> = lo..=hi;
    let len: u16 = if lo <= hi { (hi - lo) as u16 + 1 } else { 0 };
    for i in 0..steps as u16 {
        let expected = if i < len {
            Some((lo as u16 + i) as u8)
        } else {
            None
        };
        if r.next() != expected {
            return false;
        }
    }
    if steps as u16 >= len {
        r.is_empty() && !r.contains(&x)
    } else {
        !r.is_empty()
    }
}

#[cfg(kani)]
#[kani::proof]
fn range_inclusive_fresh_spec() {
    assert!(range_inclusive_fresh_spec_holds(kani::any(), kani::any()));
}

#[cfg(kani)]
#[kani::proof]
#[kani::unwind(5)]
fn range_inclusive_iterated_spec() {
    let lo: u8 = kani::any();
    let hi: u8 = kani::any();
    let steps: u8 = kani::any();
    kani::assume(steps <= 3);
    // short ranges, so that 3 steps can use them up
    kani::assume(hi <= lo.saturating_add(2));
    assert!(range_inclusive_iterated_spec_holds(
        lo,
        hi,
        steps,
        kani::any()
    ));
}

// ===========================================================================
// Regression #2603 — signed checked_rem / checked_rem_euclid
// ---------------------------------------------------------------------------
// OLD buggy spec (before PR #2606, `source/vstd/
// std_specs/num.rs`, signed `checked_rem` / `checked_rem_euclid`):
//     checked_rem:        if rhs == 0 { None } else { Some(<sign-cased rem>) }
//     checked_rem_euclid: if rhs == 0 { None }
//                         else if MIN <= lhs%rhs <= MAX { Some(lhs%rhs) }
//                         else { None }
//   Both MISS the `lhs == MIN && rhs == -1` overflow case.
//
// Current spec (`std_specs/num.rs`, signed `checked_rem` / `checked_rem_euclid`):
//     if rhs == 0 || (lhs == <$iN>::MIN && rhs == -1) { None } else { Some(..) }
//
// Real std: i8::MIN.checked_rem(-1) == None and
//           i8::MIN.checked_rem_euclid(-1) == None (the division overflows).
// ===========================================================================

/// OLD (buggy) `checked_rem` spec projection for i8, faithful to the pre-#2606
/// sign-cased body, computed over i128 to avoid intermediate overflow.
fn spec_2603_checked_rem_old_i8(lhs: i8, rhs: i8) -> Option<i8> {
    if rhs == 0 {
        return None;
    }
    let x = lhs as i128;
    let d = rhs as i128;
    let output = if x == 0 {
        0
    } else if x > 0 && d > 0 {
        x % d
    } else if x < 0 && d < 0 {
        ((x * -1) % (d * -1)) * -1
    } else if x < 0 {
        ((x * -1) % d) * -1
    } else {
        x % (d * -1)
    };
    if output < i8::MIN as i128 || output > i8::MAX as i128 {
        None
    } else {
        Some(output as i8)
    }
}

/// NEW (fixed) `checked_rem` spec projection: truncated remainder, guarded.
fn spec_2603_checked_rem_new_i8(lhs: i8, rhs: i8) -> Option<i8> {
    if rhs == 0 || (lhs == i8::MIN && rhs == -1) {
        None
    } else {
        Some(((lhs as i128) % (rhs as i128)) as i8)
    }
}

/// OLD (buggy) `checked_rem_euclid` spec projection for i8.
fn spec_2603_checked_rem_euclid_old_i8(lhs: i8, rhs: i8) -> Option<i8> {
    if rhs == 0 {
        return None;
    }
    // Verus spec `%` on `int` is Euclidean modulo.
    let m = (lhs as i128).rem_euclid(rhs as i128);
    if m >= i8::MIN as i128 && m <= i8::MAX as i128 {
        Some(m as i8)
    } else {
        None
    }
}

/// NEW (fixed) `checked_rem_euclid` spec projection: Euclidean rem, guarded.
fn spec_2603_checked_rem_euclid_new_i8(lhs: i8, rhs: i8) -> Option<i8> {
    if rhs == 0 || (lhs == i8::MIN && rhs == -1) {
        None
    } else {
        Some((lhs as i128).rem_euclid(rhs as i128) as i8)
    }
}

#[cfg(kani)]
#[kani::proof]
#[kani::should_panic] // the pre-fix spec is wrong; this assertion must fail
fn r2603_checked_rem_old_spec_is_falsifiable() {
    let lhs: i8 = kani::any();
    let rhs: i8 = kani::any();
    // MUST FAIL: at (MIN, -1) the OLD spec yields Some(0) but std yields None.
    assert_eq!(
        spec_2603_checked_rem_old_i8(lhs, rhs),
        lhs.checked_rem(rhs),
        "#2603: OLD checked_rem spec disagrees with real std"
    );
}

#[cfg(kani)]
#[kani::proof]
fn r2603_checked_rem_new_spec_holds() {
    let lhs: i8 = kani::any();
    let rhs: i8 = kani::any();
    assert_eq!(
        spec_2603_checked_rem_new_i8(lhs, rhs),
        lhs.checked_rem(rhs),
        "#2603: NEW checked_rem spec must match real std"
    );
}

