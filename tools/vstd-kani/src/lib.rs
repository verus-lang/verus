//! Kani harnesses that check Verus `vstd` `assume_specification` contracts against the real
//! Rust standard library.
//!
//! vstd's specifications of std are trusted: Verus never checks them against what std does.
//! Each harness here re-implements a specification's postcondition as plain Rust and checks
//! it against the std API it describes, for all inputs (or all inputs up to a stated bound).
//! A failing harness is a specification that disagrees with std.
//!
//! - `generated`: harnesses that `generate.py` derives mechanically from `num.rs`;
//! - `bits`, `chars`: bit counts, and the `char` and UTF-8 specifications;
//! - this file: the signed division and remainder specifications, `checked_*`/`wrapping_*`,
//!   `Option`/`Result` predicates, `RangeInclusive` bounds and `enumerate`, and regression
//!   harnesses for two specification bugs that have been fixed (#2603, #2674).
//!
//! Every `spec_*` function is plain Rust, so the crate also builds and runs its tests under
//! stock `rustc` (`cargo test`), where the harness predicates are checked exhaustively on
//! small domains with the toolchain Verus pins.

