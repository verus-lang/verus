/// vstd's `rust_div`/`rust_rem` (`vstd/arithmetic/div_mod.rs`), transcribed with
/// Euclidean `/` and `%` on unbounded integers (i64 is wide enough for i8/i16/i32 operands).
/// They are the ensures of vstd's signed `Div`/`Rem`/`DivAssign`/`RemAssign` specifications.
pub fn spec_rust_div(a: i64, b: i64) -> i64 {
    if a == 0 {
        0
    } else if a > 0 {
        a.div_euclid(b)
    } else {
        -((-a).div_euclid(b))
    }
}
pub fn spec_rust_rem(a: i64, b: i64) -> i64 {
    if a == 0 {
        0
    } else if a > 0 {
        a.rem_euclid(b)
    } else {
        -((-a).rem_euclid(b))
    }
}

#[cfg(kani)]
#[kani::proof]
fn signed_div_rem_specs_match_std_i8() {
    let a: i8 = kani::any();
    let b: i8 = kani::any();
    // the specifications' preconditions: nonzero divisor, no MIN / -1 overflow
    kani::assume(b != 0 && !(a == i8::MIN && b == -1));
    assert_eq!((a / b) as i64, spec_rust_div(a as i64, b as i64));
    assert_eq!((a % b) as i64, spec_rust_rem(a as i64, b as i64));
    let (mut x, mut y) = (a, a);
    x /= b;
    y %= b;
    assert_eq!(x as i64, spec_rust_div(a as i64, b as i64));
    assert_eq!(y as i64, spec_rust_rem(a as i64, b as i64));
}

/// vstd `std_specs/iter.rs`: `enumerate()`'s `remaining` is the inner iterator's with each
/// item paired with its position.
#[cfg(kani)]
#[kani::proof]
#[kani::unwind(5)]
fn enumerate_spec() {
    let a: [u8; 3] = kani::any();
    let mut n = 0usize;
    for (k, x) in a.iter().enumerate() {
        assert!(k == n);
        assert!(*x == a[n]);
        n += 1;
    }
    assert!(n == 3);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exhaustive_range_inclusive_specs_match_std() {
        for lo in 0..=u8::MAX {
            for hi in 0..=u8::MAX {
                assert!(range_inclusive_fresh_spec_holds(lo, hi));
                if hi <= lo.saturating_add(2) {
                    for steps in 0..=4 {
                        for x in [0, lo, hi, lo.wrapping_add(1), u8::MAX] {
                            assert!(range_inclusive_iterated_spec_holds(lo, hi, steps, x));
                        }
                    }
                }
            }
        }
    }

    #[test]
    fn replay_2603_checked_rem_min_neg1() {
        // Real std: i8::MIN.checked_rem(-1) == None.
        assert_eq!(i8::MIN.checked_rem(-1), None);
        // OLD spec disagrees (Some(0)); NEW spec agrees (None).
        assert_eq!(spec_2603_checked_rem_old_i8(i8::MIN, -1), Some(0));
        assert_eq!(spec_2603_checked_rem_new_i8(i8::MIN, -1), None);
    }

    #[test]
    fn replay_2603_checked_rem_euclid_min_neg1() {
        assert_eq!(i8::MIN.checked_rem_euclid(-1), None);
        assert_eq!(spec_2603_checked_rem_euclid_old_i8(i8::MIN, -1), Some(0));
        assert_eq!(spec_2603_checked_rem_euclid_new_i8(i8::MIN, -1), None);
    }

    #[test]
    fn exhaustive_i8_signed_div_rem_specs_match_std() {
        for a in i8::MIN..=i8::MAX {
            for b in i8::MIN..=i8::MAX {
                if b == 0 || (a == i8::MIN && b == -1) {
                    continue;
                }
                assert_eq!((a / b) as i64, super::spec_rust_div(a as i64, b as i64));
                assert_eq!((a % b) as i64, super::spec_rust_rem(a as i64, b as i64));
            }
        }
    }

    #[test]
    fn exhaustive_i8_new_specs_match_std() {
        // Exhaustive 256*256 concrete check that the NEW specs match std.
        for lhs in i8::MIN..=i8::MAX {
            for rhs in i8::MIN..=i8::MAX {
                assert_eq!(spec_2603_checked_rem_new_i8(lhs, rhs), lhs.checked_rem(rhs));
                assert_eq!(
                    spec_2603_checked_rem_euclid_new_i8(lhs, rhs),
                    lhs.checked_rem_euclid(rhs)
                );
            }
        }
    }

    #[test]
    fn exhaustive_i8_old_specs_have_a_counterexample() {
        // The OLD specs must disagree with std for at least one input.
        let mut rem_bad = false;
        let mut euclid_bad = false;
        for lhs in i8::MIN..=i8::MAX {
            for rhs in i8::MIN..=i8::MAX {
                if spec_2603_checked_rem_old_i8(lhs, rhs) != lhs.checked_rem(rhs) {
                    rem_bad = true;
                }
                if spec_2603_checked_rem_euclid_old_i8(lhs, rhs) != lhs.checked_rem_euclid(rhs) {
                    euclid_bad = true;
                }
            }
        }
        assert!(rem_bad, "OLD checked_rem spec should be falsifiable");
        assert!(
            euclid_bad,
            "OLD checked_rem_euclid spec should be falsifiable"
        );
    }
}
